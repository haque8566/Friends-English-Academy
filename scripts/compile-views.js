const fs = require("fs");
const path = require("path");
const ejs = require("ejs");

const ROOT_DIR = path.resolve(__dirname, "..");
const VIEWS_DIR = path.join(ROOT_DIR, "views");
const OUT_FILE = path.join(ROOT_DIR, "util", "views-compiled.js");

const DESTRUCTURED_LOCALS = [
    "layout",
    "body",
    "success",
    "error",
    "currentUser",
    "activeOffers",
    "user",
    "reviews",
    "avgRating",
    "totalReviews",
    "activeTab",
    "users",
    "offers",
    "contacts",
    "consultings",
    "tasks",
    "studentAttendance",
    "certificates",
    "selectedMonth",
    "todayDate",
    "userCertificates",
    "certificate",
    "qrCode",
    "currentLevel",
    "levelConfig",
    "LEVEL_CONFIG",
    "currentMonth",
    "todayTasks",
    "previousTasks",
    "completedTaskIdSet",
    "progressMap",
    "studiedDaysCount",
    "studiedDaysList",
    "isStudiedToday",
    "statusCode",
    "message"
];

function collectEjsFiles(dir) {
    const results = [];
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
        const fullPath = path.join(dir, entry.name);
        if (entry.isDirectory()) {
            results.push(...collectEjsFiles(fullPath));
        } else if (entry.isFile() && entry.name.endsWith(".ejs")) {
            results.push(fullPath);
        }
    }
    return results;
}

const files = collectEjsFiles(VIEWS_DIR).sort();
const entries = [];

for (const absPath of files) {
    const relName = path.relative(VIEWS_DIR, absPath).split(path.sep).join("/");
    const source = fs.readFileSync(absPath, "utf8");
    const templ = new ejs.Template(source, {
        client: true,
        strict: false,
        _with: false,
        compileDebug: false,
        filename: absPath,
        destructuredLocals: DESTRUCTURED_LOCALS
    });
    templ.compile();
    entries.push(`  ${JSON.stringify(relName)}: function (locals, escapeFn, include, rethrow) {\n${templ.source}\n  }`);
}

const output = `// Auto-generated by scripts/compile-views.js - do not edit manually\nmodule.exports = {\n${entries.join(",\n")}\n};\n`;
fs.writeFileSync(OUT_FILE, output, "utf8");
console.log(`Compiled ${files.length} EJS templates to ${path.relative(ROOT_DIR, OUT_FILE)}`);
